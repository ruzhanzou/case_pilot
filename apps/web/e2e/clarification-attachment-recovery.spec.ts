import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
import {writeFileSync} from 'node:fs';
test.skip(process.env.CASEPILOT_REAL_ACCEPTANCE!=='1','Requires isolated acceptance services');
test.setTimeout(420000);
test('clarification rejects expired evidence and resumes modification using its replacement',async({page},info)=>{
 const api=`${process.env.CASEPILOT_E2E_API_URL}/api/v1`;
 const post=async(path:string,data:unknown)=>{const r=await page.request.post(api+path,{data});expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
 const get=async(path:string)=>{const r=await page.request.get(api+path);expect(r.ok()).toBeTruthy();return r.json();};
 const email=`expiry-${Date.now()}@casepilot.test`;
 await page.addInitScript(()=>localStorage.setItem('casepilot.locale.v1','zh-CN'));
 const user=await post('/auth/register',{email,password:'CasePilot123!',display_name:'附件过期验收'});
 const collection=await post(`/spaces/${user.spaces[0].id}/collections`,{name:'附件生命周期验收'});
 const item=await post(`/collections/${collection.id}/test-cases`,{title:'验证码过期登录',module:'账号/验证码',priority:'P1',preconditions:['验证码已签发，测试环境可推进时钟'],steps:[{action:'等待验证码签发后420秒，提交验证码登录',expected:'登录失败，返回OLD'}]});
 const response=await page.request.put(`${api}/collections/${collection.id}/workspace`);const cid=(await response.json()).id;
 await page.goto(`/workbench/collections/${collection.id}`);
 await expect(page.locator('.principle-composer textarea')).toBeEnabled();
 await page.locator('.principle-composer textarea').fill(`修改用例 ${item.case_key}，具体修改要求我稍后补充，先等我。`);
 const initialResponse=page.waitForResponse(r=>r.url().endsWith('/messages')&&r.request().method()==='POST',{timeout:180000});
 await page.locator('.principle-composer button[type=submit]').click();const initial=await (await initialResponse).json();
 expect(initial.intent).toBe('CASE_MODIFY');
 const initialState=await get(`/conversations/${cid}`);const op=initialState.operation_plan.operations.find((o:{intent:string})=>o.intent==='CASE_MODIFY');
 expect(op.status).toBe('awaiting_target');
 const upload=async()=>{
  await expect(page.locator('.principle-composer input[type=file]')).toBeEnabled();
  await page.locator('.principle-composer input[type=file]').setInputFiles({name:'验证码规则.txt',mimeType:'text/plain',buffer:Buffer.from('验证码签发满300秒即过期，过期登录返回E731。')});
  await expect(page.locator('.principle-attachment[data-status=ready]')).toContainText('验证码规则.txt',{timeout:90000});
 };
 await upload();const before=await get(`/conversations/${cid}`);const doc=before.context.pending_attachments[0].id;
 const root=resolve(process.cwd(),'../..');execFileSync(resolve(root,'.venv/bin/python'),[resolve(root,'scripts/qa/expire_acceptance_attachment.py'),email,doc]);
 await page.reload();await expect(page.locator('.principle-attachment[data-status=expired]')).toContainText('已过期');
 const prompt='按新上传附件中的验证码规则修改该用例的操作步骤和预期结果，标题、优先级和前置条件保持不变。';
 await page.locator('.principle-composer textarea').fill(prompt);
 const attempt=page.waitForResponse(r=>r.url().endsWith('/resume')&&r.request().method()==='POST',{timeout:180000});
 await page.locator('.principle-composer button[type=submit]').click();const rejected=await attempt;
 expect(rejected.status()).toBe(422);
 await expect(page.getByText('所选附件尚未解析完成、解析失败或已失效，请等待解析完成或移除后重新上传。',{exact:true})).toBeVisible();
 await expect(page.locator('.principle-composer textarea')).toHaveValue(prompt);
 const after=await get(`/conversations/${cid}`);expect(after.messages).toEqual(before.messages);expect(after.workflow_runs).toEqual(before.workflow_runs);
 await page.getByRole('button',{name:'移除 验证码规则.txt',exact:true}).click();await expect(page.locator('.principle-attachment')).toHaveCount(0);
 await upload();const replacement=await get(`/conversations/${cid}`);expect(replacement.context.pending_attachments[0].id).not.toBe(doc);
 await page.reload();await expect(page.locator('.principle-attachment[data-status=ready]')).toBeVisible();
 await page.locator('.principle-composer textarea').fill(prompt);
 const accepted=page.waitForResponse(r=>r.url().endsWith('/resume')&&r.request().method()==='POST',{timeout:180000});
 await page.locator('.principle-composer button[type=submit]').click();const fresh=await accepted;expect(fresh.status()).toBe(202);const turn=await fresh.json();
 expect(turn.intent).toBe('CASE_MODIFY');
 expect(await get(`/collections/${collection.id}/test-cases`)).toEqual([item]);
 const confirmation=page.waitForResponse(r=>r.url().endsWith('/resume')&&r.request().method()==='POST',{timeout:180000});
 await page.getByRole('button',{name:'确认修改并生成建议',exact:true}).last().click();const confirmed=await (await confirmation).json();
 expect(confirmed.action.job_id).toBeTruthy();
 let finished=await get(`/conversations/${cid}`);
 await expect.poll(async()=>{finished=await get(`/conversations/${cid}`);const run=finished.workflow_runs.find((r:{job_id:string})=>r.job_id===confirmed.action.job_id);if(run?.status==='failed')throw Error(JSON.stringify(run));return run?.status;},{timeout:180000}).toBe('completed');
 const change=await get(`/case-change-sets/${confirmed.action.change_set_id}`);
 expect(change.items).toHaveLength(1);const proposed=change.items[0].proposed_snapshot;
 expect(JSON.stringify(proposed.steps)).toContain('E731');expect(JSON.stringify(proposed.steps)).toContain('300');
 expect(proposed.title).toBe(item.title);expect(proposed.priority).toBe(item.priority);expect(proposed.preconditions).toEqual(item.preconditions);
 expect(await get(`/collections/${collection.id}/test-cases`)).toEqual([item]);
 const finalOperation=finished.operation_plan.operations.find((o:{id:string})=>o.id===op.id);
 expect(finalOperation.payload.attachment_context.document_ids).toContain(replacement.context.pending_attachments[0].id);
 expect(finished.context.document_ids).not.toContain(doc);
 writeFileSync(info.outputPath('evidence.json'),JSON.stringify({email,doc,status:rejected.status(),replacement:replacement.context.pending_attachments,turn,confirmed,change,finalOperation},null,2));
 await expect(page.locator('.collection-changes__review').getByRole('button',{name:/一键采纳全部待审阅用例/})).toBeEnabled({timeout:60000});
 await expect(page.getByRole('button',{name:'结束任务',exact:true})).toHaveCount(0);
 await page.reload();
 await expect(page.locator('.collection-changes__review').getByRole('button',{name:/一键采纳全部待审阅用例/})).toBeEnabled({timeout:60000});
 expect(await get(`/collections/${collection.id}/test-cases`)).toEqual([item]);
 await page.screenshot({path:info.outputPath('replacement-ready.png'),fullPage:true});
});
