import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
import {writeFileSync} from 'node:fs';
test.skip(process.env.CASEPILOT_REAL_ACCEPTANCE!=='1','Requires isolated acceptance services');
test.setTimeout(420000);
test('natural language query selects complete compound scope from 5001 persisted cases',async({page},info)=>{
 const api=`${process.env.CASEPILOT_E2E_API_URL}/api/v1`;
 const post=async(path:string,data:unknown)=>{const r=await page.request.post(api+path,{data});expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
 const email=`large-scope-${Date.now()}@casepilot.test`;
 const user=await post('/auth/register',{email,password:'CasePilot123!',display_name:'大范围查询验收'});
 const collection=await post(`/spaces/${user.spaces[0].id}/collections`,{name:'5001条用例查询验收'});
 const root=resolve(process.cwd(),'../..');const fixture=JSON.parse(execFileSync(resolve(root,'.venv/bin/python'),[resolve(root,'scripts/qa/seed_large_scope_acceptance.py'),email,collection.id],{encoding:'utf8',timeout:120000}));
 await page.addInitScript(()=>localStorage.setItem('casepilot.locale.v1','zh-CN'));
 await page.goto(`/workbench/collections/${collection.id}`);
 await expect(page.locator('.principle-composer textarea')).toBeEnabled({timeout:60000});
 await page.locator('.principle-composer textarea').fill('查询支付模块及其子模块中步骤包含“回滚”的正式用例，排除P0。只查询，不修改。');
 const started=Date.now();const pending=page.waitForResponse(r=>r.url().endsWith('/messages')&&r.request().method()==='POST',{timeout:240000});
 await page.locator('.principle-composer button[type=submit]').click();const response=await pending;expect(response.ok(),await response.text()).toBeTruthy();const turn=await response.json();
 expect(turn.intent).toBe('CASE_QUERY');expect(turn.action.count).toBe(fixture.expected_ids.length);
 expect(new Set(turn.assistant_message.target_case_ids)).toEqual(new Set(fixture.expected_ids));
 await expect(page.locator('.principle-composer textarea')).toBeEnabled({timeout:60000});
 await page.reload();await expect(page.locator('.principle-composer textarea')).toBeEnabled({timeout:60000});
 const state=await(await page.request.get(`${api}/conversations/${turn.conversation_id}`)).json();
 const saved=state.messages.find((m:{id:string})=>m.id===turn.assistant_message.id);
 expect(new Set(saved.target_case_ids)).toEqual(new Set(fixture.expected_ids));
 const follow=async(content:string)=>{
  await page.locator('.principle-composer textarea').fill(content);
  const wait=page.waitForResponse(r=>r.url().endsWith('/messages')&&r.request().method()==='POST',{timeout:240000});
  await page.locator('.principle-composer button[type=submit]').click();const r=await wait;expect(r.ok(),await r.text()).toBeTruthy();
  const result=await r.json();await expect(page.locator('.principle-composer textarea')).toBeEnabled({timeout:60000});return result;
 };
 const narrowed=await follow('只在刚才查询结果中查找编号 BIG-05000 的用例，不能扩大到其他范围。');
 expect(narrowed.intent).toBe('CASE_QUERY');expect(narrowed.action.count).toBe(0);
 const deletion=await follow('删除刚才查询到的用例，不扩大范围。');
 expect(deletion.action.change_set_id).toBeFalsy();
 const unchanged=await(await page.request.get(`${api}/collections/${collection.id}/test-cases`)).json();
 expect(unchanged).toHaveLength(5001);
 writeFileSync(info.outputPath('evidence.json'),JSON.stringify({email,collection:collection.id,count:fixture.count,expectedCount:fixture.expected_ids.length,turn,narrowed,deletion,elapsedMs:Date.now()-started},null,2));
 await page.screenshot({path:info.outputPath('large-query.png'),fullPage:true});
});
