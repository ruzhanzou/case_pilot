import {test, expect} from '@playwright/test';
import {readFileSync, writeFileSync} from 'node:fs';
test.skip(!process.env.CASEPILOT_PARTIAL_GENERATION_FIXTURE, 'Requires synthetic recovered generation fixture');
test.setTimeout(240000);
test('natural mixed deletion reviews exact scope and partial confirmation survives refresh', async ({page},info) => {
 const fixture=JSON.parse(readFileSync(process.env.CASEPILOT_PARTIAL_GENERATION_FIXTURE!,'utf8'));
 expect(fixture.email.endsWith('@casepilot.test')).toBeTruthy();
 const api=`${process.env.CASEPILOT_E2E_API_URL}/api/v1`;
 await page.addInitScript(()=>localStorage.setItem('casepilot.locale.v1','zh-CN'));
 expect((await page.request.post(`${api}/auth/login`,{data:{email:fixture.email,password:'CasePilot123!'}})).ok()).toBeTruthy();
 const get=async(path:string)=>{const r=await page.request.get(api+path);expect(r.ok(), await r.text()).toBeTruthy();return r.json();};
 const before=await get(`/conversations/${fixture.conversation_id}`);expect(before.candidates.length).toBeGreaterThanOrEqual(2);
 const candidate=before.candidates[0], sibling=before.candidates[1];
 const baseline=await get(`/collections/${fixture.collection_id}/test-cases`);
 const created=await page.request.post(`${api}/collections/${fixture.collection_id}/test-cases`,{data:{title:'混合删除验收正式用例',module:'账号',priority:'P1',preconditions:['账号有效'],steps:[{action:'提交登录',expected:'进入首页'}]}});
 expect(created.ok()).toBeTruthy();const formal=await created.json();
 await page.goto(`/workbench/collections/${fixture.collection_id}`);
 const send=async(content:string)=>{const composer=page.locator('.principle-composer textarea');await expect(composer).toBeEnabled();await composer.fill(content);const wait=page.waitForResponse(r=>r.url().endsWith('/messages')&&r.request().method()==='POST',{timeout:120000});await page.locator('.principle-composer button[type=submit]').click();const r=await wait;expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
 const turn=await send(`删除正式用例 ${formal.case_key} 和候选 ${candidate.ref}，只处理这两条，其他用例和候选保持不变。`);
 writeFileSync(info.outputPath('turn.json'),JSON.stringify(turn,null,2));
 expect(turn.intent).toBe('CASE_DELETE');
 expect(turn.action.change_set_id).toBeTruthy();
 const path=`/case-change-sets/${turn.action.change_set_id}`;const change=await get(path);
 expect(change.items.map((item:{target_type:string})=>item.target_type).sort()).toEqual(['candidate','formal']);
 expect(new Set(change.items.map((item:{ref:string})=>item.ref))).toEqual(new Set([formal.id,candidate.ref]));
 expect((await get(`/conversations/${fixture.conversation_id}`)).candidates).toEqual(before.candidates);
 await page.reload();const review=page.locator('.collection-changes__review');
 await review.getByRole('checkbox',{name:'软删除此正式用例',exact:true}).uncheck();
 const applied=page.waitForResponse(r=>r.url().endsWith('/apply')&&r.request().method()==='POST');
 await review.getByRole('button',{name:'确认删除已选用例',exact:true}).click();
 expect((await applied).ok()).toBeTruthy();
 await page.reload();const after=await get(`/conversations/${fixture.conversation_id}`);
 expect(after.candidates.some((item:{id:string})=>item.id===candidate.id)).toBe(false);
 expect(after.candidates.find((item:{id:string})=>item.id===sibling.id)).toEqual(sibling);
 expect(await get(`/collections/${fixture.collection_id}/test-cases`)).toEqual([...baseline,formal]);
 const saved=await get(path);expect(saved.items.find((item:{ref:string})=>item.ref===candidate.ref).status).toBe('applied');
 expect(saved.items.find((item:{ref:string})=>item.ref===formal.id).status).toBe('rejected');
 const repeated=await page.request.post(api+path+'/apply',{data:{accepted_fields:{[candidate.ref]:['delete'],[formal.id]:[]}}});expect(repeated.ok()).toBeTruthy();
 expect((await get(`/conversations/${fixture.conversation_id}`)).candidates).toEqual(after.candidates);
 const last=await send(`删除用例 ${formal.case_key}`);expect(last.intent).toBe('CASE_DELETE');
 await page.getByRole('button',{name:'确认删除已选用例',exact:true}).click();
 await expect.poll(async()=> (await get(`/collections/${fixture.collection_id}/test-cases`)).length).toBe(baseline.length);
 await page.reload();expect((await get(`/conversations/${fixture.conversation_id}`)).candidates.find((item:{id:string})=>item.id===sibling.id)).toEqual(sibling);
 writeFileSync(info.outputPath('evidence.json'),JSON.stringify({turn,change,saved,after,last},null,2));
 await page.screenshot({path:info.outputPath('mixed-delete.png'),fullPage:true});
});

test('deleting final candidate closes generation and next request starts a new scope', async ({page},info) => {
 const fixture=JSON.parse(readFileSync(process.env.CASEPILOT_PARTIAL_GENERATION_FIXTURE!,'utf8'));
 const api=`${process.env.CASEPILOT_E2E_API_URL}/api/v1`;
 await page.addInitScript(()=>localStorage.setItem('casepilot.locale.v1','zh-CN'));
 expect((await page.request.post(`${api}/auth/login`,{data:{email:fixture.email,password:'CasePilot123!'}})).ok()).toBeTruthy();
 const get=async(path:string)=>{const r=await page.request.get(api+path);expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
 const before=await get(`/conversations/${fixture.conversation_id}`);expect(before.candidates).toHaveLength(1);
 const formalBefore=await get(`/collections/${fixture.collection_id}/test-cases`);
 await page.goto(`/workbench/collections/${fixture.collection_id}`);
 const send=async(content:string)=>{const composer=page.locator('.principle-composer textarea');await expect(composer).toBeEnabled();await composer.fill(content);const wait=page.waitForResponse(r=>r.url().endsWith('/messages')&&r.request().method()==='POST',{timeout:120000});await page.locator('.principle-composer button[type=submit]').click();const r=await wait;expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
 await send(`删除候选 ${before.candidates[0].ref}`);
 await page.getByRole('button',{name:'确认删除已选用例',exact:true}).click();
 await expect.poll(async()=> (await get(`/conversations/${fixture.conversation_id}`)).candidates.length).toBe(0);
 await page.reload();const closed=await get(`/conversations/${fixture.conversation_id}`);
 expect(closed.context.active_mutation_task_id).toBeNull();expect(closed.context.phase).toBe('maintenance');
 expect(await get(`/collections/${fixture.collection_id}/test-cases`)).toEqual(formalBefore);
 const next=await send('测试对象：退款系统。新增1条退款用例，仅包含已退款订单禁止再次退款并提示重复退款这个场景，先规划，不生成用例。');
 expect(next.intent).toBe('CASE_GENERATE');
 expect(next.operation_plan.operations.at(-1).payload.task_id).not.toBe(before.context.active_mutation_task_id);
 let after=closed;await expect.poll(async()=>{after=await get(`/conversations/${fixture.conversation_id}`);return after.workflow_runs.find((r:{job_id:string})=>r.job_id===next.action.job_id)?.status;},{timeout:180000}).toBe('completed');
 expect(after.test_briefs.at(-1).content.planning.test_points).toHaveLength(1);
 expect(JSON.stringify(after.test_briefs.at(-1).content.planning)).not.toContain('验证码');
 writeFileSync(info.outputPath('evidence.json'),JSON.stringify({closed,next,after},null,2));
 await page.screenshot({path:info.outputPath('new-scope.png'),fullPage:true});
});
