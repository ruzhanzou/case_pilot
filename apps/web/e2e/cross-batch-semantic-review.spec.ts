import {test,expect} from '@playwright/test';
import {writeFileSync} from 'node:fs';
test.skip(process.env.CASEPILOT_REAL_ACCEPTANCE!=='1','Requires isolated real services');
test.setTimeout(600000);
test('semantic duplicates across batches are found while distinct account states remain separate',async({page},info)=>{
 const api=`${process.env.CASEPILOT_E2E_API_URL}/api/v1`;
 const post=async(path:string,data:unknown)=>{const r=await page.request.post(api+path,{data});expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
 const get=async(path:string)=>{const r=await page.request.get(api+path);expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
 await page.addInitScript(()=>localStorage.setItem('casepilot.locale.v1','zh-CN'));
 const user=await post('/auth/register',{email:`dedup-${Date.now()}@casepilot.test`,password:'CasePilot123!',display_name:'跨批查重验收'});
 const collection=await post(`/spaces/${user.spaces[0].id}/collections`,{name:'跨批次完整原文查重'});
 const common={module:'账号/登录',priority:'P1',case_type:'功能'};
 const left=await post(`/collections/${collection.id}/test-cases`,{...common,title:'A 正常凭据登录',preconditions:['账号处于启用状态，密码正确'],steps:[{action:'填写账号和正确密码，点击登录',expected:'认证成功并进入系统首页'}]});
 for(let i=0;i<19;i++) await post(`/collections/${collection.id}/test-cases`,{...common,title:`L 独立库存操作${i}`,module:`库存独立模块${i}`,preconditions:[`商品${i}库存不足`],steps:[{action:`提交商品${i}的订单`,expected:`拒绝商品${i}订单并显示库存不足`} ]});
 const distinct=await post(`/collections/${collection.id}/test-cases`,{...common,title:'Y 禁用账户验证',preconditions:['账号已被禁用，密码正确'],steps:[{action:'填写账号和正确密码，点击登录',expected:'拒绝登录并提示账户已禁用，不进入首页'}]});
 const right=await post(`/collections/${collection.id}/test-cases`,{...common,title:'Z 有效用户进入主页',preconditions:['用户账号可用且未停用，提供匹配的口令'],steps:[{action:'在登录页提交有效用户名及匹配口令',expected:'身份验证通过，展示应用主页'}]});
 const before=await get(`/collections/${collection.id}/test-cases`);
 const workspace=await page.request.put(`${api}/collections/${collection.id}/workspace`);expect(workspace.ok()).toBeTruthy();const cid=(await workspace.json()).id;
 await page.goto(`/workbench/collections/${collection.id}`);
 const composer=page.locator('.principle-composer textarea');await composer.fill('检查当前集合所有22条用例的重复关系，只检查，不修改或删除任何用例。');
 const wait=page.waitForResponse(r=>r.url().endsWith('/messages')&&r.request().method()==='POST',{timeout:180000});
 await page.locator('.principle-composer button[type=submit]').click();const r=await wait;expect(r.ok(),await r.text()).toBeTruthy();const turn=await r.json();
 expect(turn.intent).toBe('CASE_DEDUP');
 if(process.env.CASEPILOT_QA_ANALYSIS_PROGRESS==='1'){
   let progress;
   let startedAt: string | undefined;
   await expect.poll(async()=>{
     const job=await get(`/generation-jobs/${turn.action.job_id}`);
     progress=job.analysis_progress;
     startedAt=job.started_at;
     return Boolean(progress&&progress.total_batches>0&&(progress.completed_batches>0||progress.total_batches===1));
   },{timeout:240000}).toBe(true);
   writeFileSync(info.outputPath('running-progress.json'),JSON.stringify(progress,null,2));
   await page.reload();
   await expect(page.locator('.case-conversation-running').filter({hasText:'分析用例'})).toContainText(/已完成 \d+\/[1-9]\d* 批/,{timeout:30000});
   const restored=await get(`/generation-jobs/${turn.action.job_id}`);
   expect(restored.analysis_progress.completed_batches).toBeGreaterThanOrEqual(progress!.completed_batches);
   expect(restored.progress).toBeGreaterThanOrEqual(10);
   expect(startedAt).toBeTruthy();
   expect(restored.started_at).toBe(startedAt);
   const minimumElapsed=Math.floor((Date.now()-Date.parse(startedAt!))/1000)-5;
   await expect.poll(async()=>Number((await page.locator('.case-conversation-running').filter({hasText:'分析用例'}).innerText()).match(/已等待 (\d+) 秒/)?.[1]??0)).toBeGreaterThanOrEqual(minimumElapsed);
   await page.screenshot({path:info.outputPath('progress-after-reload.png'),fullPage:true});
 }
 let state=await get(`/conversations/${cid}`);
 await expect.poll(async()=>{state=await get(`/conversations/${cid}`);const run=state.workflow_runs.find((item:{job_id:string})=>item.job_id===turn.action.job_id);if(run?.status==='failed')throw Error(JSON.stringify(run));return run?.status;},{timeout:480000}).toBe('completed');
 const message=state.messages.findLast((m:{metadata:{analysis_report?:unknown}})=>m.metadata.analysis_report);
 const report=message.metadata.analysis_report;
 expect(report.findings.some((f:{relationship:string;case_refs:string[]})=>f.relationship==='duplicate'&&f.case_refs.includes(left.id)&&f.case_refs.includes(right.id))).toBe(true);
 expect(report.findings.some((f:{relationship:string;case_refs:string[]})=>f.relationship==='duplicate'&&f.case_refs.includes(distinct.id)&&(f.case_refs.includes(left.id)||f.case_refs.includes(right.id)))).toBe(false);
 expect(report.limitations.join(' ')).toContain('231/231');
 expect(report.limitations.join(' ')).not.toMatch(/(?:剩余|其余)\s*\d+\s*条.*(?:未提供|未纳入)|仅(?:获取到|提供)\s*\d+\s*条/);
 expect(await get(`/collections/${collection.id}/test-cases`)).toEqual(before);
 await page.reload();await expect(page.locator('.principle-composer textarea')).toBeEnabled();
 expect(await get(`/collections/${collection.id}/test-cases`)).toEqual(before);
 writeFileSync(info.outputPath('evidence.json'),JSON.stringify({turn,report,left,right,distinct},null,2));
 await expect(page.getByRole('heading',{name:'跨批次完整原文查重',exact:true})).toBeVisible();
 await page.screenshot({path:info.outputPath('cross-batch-review.png'),fullPage:true});
});
