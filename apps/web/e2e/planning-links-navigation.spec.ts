import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
const api = process.env.CASEPILOT_E2E_API_URL ?? 'http://localhost:8015';
const output = path.resolve('../../output/multi-requirement-eval-20261015');
test.skip(process.env.CASEPILOT_REAL_ACCEPTANCE !== '1', 'Requires completed multi-requirement fixtures');
test.use({ viewport: { width: 1600, height: 1100 } });
for (const id of ['E01', 'E02']) test(`${id}: navigate from test point to formal case and back to the exact planning version`, async ({ page }) => {
  const fixture = JSON.parse(await readFile(path.join(output, `${id}-fixture.json`), 'utf8'));
  const result = JSON.parse(await readFile(path.join(output, `${id}-result.json`), 'utf8'));
  await page.addInitScript(() => localStorage.setItem('casepilot.locale.v1', 'zh-CN'));
  const login = await page.request.post(`${api}/api/v1/auth/login`, { data: { email: fixture.email, password: 'CasePilot123!' } });
  expect(login.status()).toBe(200);
  const link = result.links.find((item: { origin: string }) => item.origin === 'generated');
  const point = result.plan.test_points.find((item: { id: string }) => item.id === link.test_point_id);
  await page.goto(`/workbench/collections/${fixture.collection.id}`);
  await page.getByRole('button', { name: '结构化测试说明', exact: true }).click();
  await page.getByLabel('规划展开层级').selectOption('20');
  await page.getByRole('button', { name: `查看复用依据：${point.title}`, exact: true }).click();
  const detail = page.getByRole('complementary', { name: '测试点详情' });
  await detail.getByRole('button', { name: `${link.case_key} · ${link.title}`, exact: true }).click();
  const reverse = page.getByRole('region', { name: '关联测试点' });
  await expect(reverse).toContainText(point.title);
  await page.screenshot({ path: path.join(output, `${id}-reverse-links.png`), fullPage: true });
  await reverse.getByRole('button', { name: `V${link.brief_version} · ${point.title}`, exact: true }).click();
  await expect(detail).toContainText(point.title);
  await expect(detail.getByRole('region', { name: '关联用例' })).toContainText(link.case_key);
  await page.screenshot({ path: path.join(output, `${id}-navigation-final.png`), fullPage: true });
});
